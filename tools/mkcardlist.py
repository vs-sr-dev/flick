"""mkcardlist.py <hyperscan_card.xml> > src/cardlist.c

Builds the card catalogue from MAME's software list (hash/hyperscan_card.xml, CC0-1.0).
Every card in that list is a generated image: zero UID, bytes 8-9 = game ID and 10-11 =
card number, little-endian except Marvel Heroes (big-endian). This script checks that
claim against each listed CRC before emitting the entry.
"""
import html
import re
import sys
import zlib

GAMES = {  # list prefix -> (enum, game id, big-endian)
    "iwl": ("CARD_IWL", 1, False),
    "ben": ("CARD_BEN10", 2, False),
    "xmen": ("CARD_XMEN", 3, False),
    "marvh": ("CARD_MARVEL", 4, True),
    "spdrm": ("CARD_SPIDERMAN", 5, False),
}


def image(gid, num, be):
    b = bytearray(120)
    order = "big" if be else "little"
    b[8:10] = gid.to_bytes(2, order)
    b[10:12] = num.to_bytes(2, order)
    return bytes(b)


xml = open(sys.argv[1], encoding="utf-8").read()
out = []
entries = re.findall(r'<software name="([a-z]+)(\d+)"(.*?)</software>', xml, re.S)
entries.sort(key=lambda e: (e[0], int(e[1])))   # by game, then card number
for prefix, num, body in entries:
    enum, gid, be = GAMES[prefix]
    desc = html.unescape(re.search(r"<description>(.*?)</description>", body).group(1))
    crc = int(re.search(r'crc="([0-9a-f]+)"', body).group(1), 16)
    if zlib.crc32(image(gid, int(num), be)) != crc:
        sys.exit(f"{prefix}{num}: CRC does not match the generated image")
    name = desc.split(": ", 1)[1] if ": " in desc else desc
    out.append(f'\t{{ {enum}, {int(num)}, "{prefix}{num}", "{name.replace(chr(34), chr(92) + chr(34))}" }},')

print("/* Generated by tools/mkcardlist.py from MAME's hash/hyperscan_card.xml (CC0-1.0). */")
print('#include "cards.h"')
print()
print("const card_info g_card_list[] = {")
print("\n".join(out))
print("};")
print(f"const int g_card_count = {len(out)};")
